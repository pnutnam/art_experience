#!/usr/bin/env python3
"""Generate narration audio for The Keppler Rooms from data/tour.json.

Reads the tour script, synthesizes each beat with edge-tts (Microsoft neural
voices), measures durations with ffprobe, and emits js/tour-data.js with
everything the web app needs. Re-runs are incremental: beats whose text hash
matches an existing manifest entry are skipped.

Usage:  work/venv/bin/python build/generate_audio.py
"""
import asyncio
import hashlib
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOUR = json.loads((ROOT / "data" / "tour.json").read_text())
AUDIO_DIR = ROOT / "assets" / "audio"
MANIFEST = AUDIO_DIR / "manifest.json"
OUT_JS = ROOT / "js" / "tour-data.js"

VOICE = TOUR["meta"].get("voice", "en-US-AndrewNeural")
RATE = TOUR["meta"].get("rate", "-8%")


def collect_beats():
    """Flatten the tour into (id, text) pairs."""
    beats = []
    for b in TOUR["welcome"]["beats"]:
        if b.get("audio"):
            beats.append((b["id"], b["audio"]))
    for stop in TOUR["stops"]:
        for b in stop["beats"]:
            if b.get("audio"):
                beats.append((b["id"], b["audio"]))
    return beats


def text_hash(text: str) -> str:
    return hashlib.sha256(f"{VOICE}|{RATE}|{text}".encode()).hexdigest()[:16]


def duration_of(path: Path) -> float:
    out = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration",
         "-of", "csv=p=0", str(path)],
        capture_output=True, text=True, check=True,
    )
    return round(float(out.stdout.strip()), 3)


async def synth(edge_tts, beat_id: str, text: str, out_path: Path):
    com = edge_tts.Communicate(text, VOICE, rate=RATE)
    await com.save(str(out_path))


async def main():
    import edge_tts  # noqa: F401  (import here so --help works without it)

    AUDIO_DIR.mkdir(parents=True, exist_ok=True)
    manifest = {}
    if MANIFEST.exists():
        manifest = json.loads(MANIFEST.read_text())

    beats = collect_beats()
    todo = []
    for beat_id, text in beats:
        h = text_hash(text)
        mp3 = AUDIO_DIR / f"{beat_id}.mp3"
        entry = manifest.get(beat_id)
        if entry and entry["hash"] == h and mp3.exists() and mp3.stat().st_size > 2000:
            continue  # up to date
        todo.append((beat_id, text, h, mp3))

    print(f"{len(beats)} beats total, {len(todo)} to synthesize (voice {VOICE}, rate {RATE})")
    failed = []
    for i, (beat_id, text, h, mp3) in enumerate(todo, 1):
        ok = False
        for attempt in range(3):
            try:
                await synth(edge_tts, beat_id, text, mp3)
                if mp3.exists() and mp3.stat().st_size > 2000:
                    ok = True
                    break
            except Exception as e:  # noqa: BLE001
                print(f"  retry {beat_id} ({attempt+1}): {e}")
                await asyncio.sleep(2 + attempt * 3)
        if not ok:
            print(f"  !! FAILED to synthesize {beat_id} (continuing; app falls back to device voice)")
            failed.append(beat_id)
            if mp3.exists() and mp3.stat().st_size <= 2000:
                mp3.unlink()  # don't leave a truncated file
        else:
            print(f"  [{i}/{len(todo)}] {beat_id}.mp3  {mp3.stat().st_size//1024} KB")

    # Measure durations for every beat that has a healthy file; refresh manifest
    # (preserving extra keys like "provider" set by adopt_external_audio.py).
    durations = {}
    for beat_id, text in beats:
        mp3 = AUDIO_DIR / f"{beat_id}.mp3"
        if mp3.exists() and mp3.stat().st_size > 2000:
            durations[beat_id] = duration_of(mp3)
            manifest[beat_id] = {**manifest.get(beat_id, {}),
                                 "hash": text_hash(text), "file": mp3.name}

    MANIFEST.write_text(json.dumps(manifest, indent=1))
    total = sum(durations.values())
    print(f"total narration: {total/60:.1f} minutes")

    payload = {
        "meta": TOUR["meta"],
        "welcome": TOUR["welcome"],
        "stops": TOUR["stops"],
        "durations": durations,
        "audioBase": "assets/audio/",
        "images": {
            name: {
                "mid": f"assets/img/{name}_mid.jpg",
                "full": f"assets/img/{name}_full.jpg",
                "webp": f"assets/img/{name}_full.webp",
                "thumb": f"assets/img/{name}_thumb.jpg",
            }
            for name in ("sheol", "prodigal_father", "yorktown", "bosses_senate")
        },
    }
    OUT_JS.write_text(
        "// Generated by build/generate_audio.py — do not edit by hand.\n"
        "window.TOUR_DATA = " + json.dumps(payload, ensure_ascii=False) + ";\n"
    )
    print(f"wrote {OUT_JS} ({OUT_JS.stat().st_size//1024} KB)")

    # Cache-bust the generated files in index.html so returning visitors
    # always get fresh tour data (static hosting sends no useful headers).
    import re
    import hashlib
    idx = ROOT / "index.html"
    html = idx.read_text()
    for fname in ("tour-data.js", "lqip.js"):
        fhash = hashlib.sha1((ROOT / "js" / fname).read_bytes()).hexdigest()[:8]
        html = re.sub(
            rf"js/{fname}(\?v=[0-9a-f]+)?",
            f"js/{fname}?v={fhash}",
            html,
        )
    idx.write_text(html)
    print("cache-busted index.html script tags")


if __name__ == "__main__":
    asyncio.run(main())
